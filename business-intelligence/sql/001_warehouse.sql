-- StreamShield dimensional warehouse. Run after the operational schema migrations.
CREATE SCHEMA IF NOT EXISTS bi;

CREATE TABLE IF NOT EXISTS bi.dim_date (
    date_key integer PRIMARY KEY,
    full_date date NOT NULL UNIQUE,
    year smallint NOT NULL,
    quarter smallint NOT NULL,
    month smallint NOT NULL,
    month_name text NOT NULL,
    day_of_month smallint NOT NULL,
    iso_week smallint NOT NULL,
    day_of_week smallint NOT NULL
);

CREATE TABLE IF NOT EXISTS bi.dim_platform (
    platform_key text PRIMARY KEY,
    platform_name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS bi.dim_streamer (
    streamer_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    streamer_id uuid NOT NULL UNIQUE,
    tenant_id uuid NOT NULL,
    username text NOT NULL,
    role text NOT NULL,
    created_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS bi.dim_stream (
    stream_key bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id uuid NOT NULL UNIQUE,
    tenant_id uuid NOT NULL,
    streamer_id uuid NOT NULL REFERENCES bi.dim_streamer(streamer_id),
    platform_key text NOT NULL REFERENCES bi.dim_platform(platform_key),
    channel_name text NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS bi.user_tenant_access (
    db_role name PRIMARY KEY,
    tenant_id uuid NOT NULL
);

CREATE OR REPLACE FUNCTION bi.current_tenant_id()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = bi, pg_temp
AS $$
    SELECT tenant_id FROM bi.user_tenant_access WHERE db_role = session_user::name
$$;

CREATE TABLE IF NOT EXISTS bi.fact_stream_snapshot (
    stream_id uuid NOT NULL REFERENCES bi.dim_stream(stream_id),
    snapshot_date date NOT NULL REFERENCES bi.dim_date(full_date),
    platform_key text NOT NULL REFERENCES bi.dim_platform(platform_key),
    is_live boolean NOT NULL,
    viewer_count integer NOT NULL DEFAULT 0 CHECK (viewer_count >= 0),
    active_chatters integer NOT NULL DEFAULT 0 CHECK (active_chatters >= 0),
    suspicious_viewers integer NOT NULL DEFAULT 0 CHECK (suspicious_viewers >= 0),
    active_attacks integer NOT NULL DEFAULT 0 CHECK (active_attacks >= 0),
    engagement_rate numeric(7,4) NOT NULL DEFAULT 0,
    threat_score numeric(7,4) NOT NULL DEFAULT 0,
    loaded_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (stream_id, snapshot_date)
);

CREATE TABLE IF NOT EXISTS bi.fact_viewer_session (
    session_id uuid PRIMARY KEY,
    stream_id uuid NOT NULL REFERENCES bi.dim_stream(stream_id),
    joined_date date NOT NULL REFERENCES bi.dim_date(full_date),
    joined_at timestamptz NOT NULL,
    left_at timestamptz,
    is_active boolean NOT NULL,
    is_suspected_bot boolean NOT NULL,
    risk_score numeric(7,4) NOT NULL DEFAULT 0,
    chat_messages integer NOT NULL DEFAULT 0,
    watch_duration_seconds integer NOT NULL DEFAULT 0,
    source text NOT NULL DEFAULT 'unknown',
    loaded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bi.fact_attack (
    attack_id uuid PRIMARY KEY,
    stream_id uuid NOT NULL REFERENCES bi.dim_stream(stream_id),
    created_date date NOT NULL REFERENCES bi.dim_date(full_date),
    attack_type text NOT NULL,
    severity text NOT NULL,
    status text NOT NULL,
    risk_score numeric(7,4) NOT NULL DEFAULT 0,
    confidence numeric(7,4) NOT NULL DEFAULT 0,
    affected_users integer NOT NULL DEFAULT 0,
    mitigation_action text NOT NULL DEFAULT 'none',
    created_at timestamptz NOT NULL,
    mitigated_at timestamptz,
    resolved_at timestamptz,
    loaded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS bi.fact_chat_activity (
    stream_id uuid NOT NULL REFERENCES bi.dim_stream(stream_id),
    activity_date date NOT NULL REFERENCES bi.dim_date(full_date),
    event_type text NOT NULL,
    messages bigint NOT NULL DEFAULT 0,
    unique_users bigint NOT NULL DEFAULT 0,
    suspicious_messages bigint NOT NULL DEFAULT 0,
    average_risk_score numeric(7,4) NOT NULL DEFAULT 0,
    loaded_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (stream_id, activity_date, event_type)
);

CREATE INDEX IF NOT EXISTS ix_bi_stream_snapshot_date ON bi.fact_stream_snapshot(snapshot_date);
CREATE INDEX IF NOT EXISTS ix_bi_viewer_joined_date ON bi.fact_viewer_session(joined_date);
CREATE INDEX IF NOT EXISTS ix_bi_attack_created_date ON bi.fact_attack(created_date);
CREATE INDEX IF NOT EXISTS ix_bi_chat_activity_date ON bi.fact_chat_activity(activity_date);

